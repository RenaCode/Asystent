import SwiftUI

struct ContentView: View {
    @Environment(AssistantSession.self) private var session
    @State private var typed = ""
    @State private var showSettings = false
    @Environment(\.openURL) private var openURL

    var body: some View {
        @Bindable var session = session
        NavigationStack {
            VStack(spacing: 16) {
                ScrollView {
                    VStack(alignment: .leading, spacing: 10) {
                        ForEach(session.lines) { line in
                            Text("**\(line.role == .user ? String(localized: "You") : String(localized: "Hejo (AI)")):** \(line.text)")
                                .frame(maxWidth: .infinity, alignment: .leading)
                                .contextMenu {
                                    // App Review 1.2: zgłoszenie treści wygenerowanej przez AI (e-mail od użytkownika).
                                    if line.role == .assistant, let url = AnswerReport.mailURL(answer: line.text) {
                                        Button("Report answer", systemImage: "flag") { openURL(url) }
                                    }
                                }
                        }
                    }
                    .padding()
                }
                .accessibilityIdentifier("conversation")

                // AI Act art. 50(1): stała informacja, że odpowiada AI.
                Text("Answers are generated by AI (Claude by Anthropic) and may be inaccurate. Touch and hold an answer to report it.")
                    .font(.caption2)
                    .foregroundStyle(.secondary)
                    .multilineTextAlignment(.center)
                    .padding(.horizontal)
                    .accessibilityIdentifier("aiNotice")

                if session.phase == .listening {
                    Text(session.transcript.isEmpty ? String(localized: "Listening…") : session.transcript)
                        .foregroundStyle(.secondary)
                }
                if case .error(let msg) = session.phase {
                    Text(msg).foregroundStyle(.red).font(.footnote)
                        .accessibilityIdentifier("errorText")
                }

                if case .confirming = session.phase {
                    HStack(spacing: 24) {
                        Button("No", role: .cancel) { session.answerConfirmation(false) }
                        Button("Yes") { session.answerConfirmation(true) }
                            .buttonStyle(.borderedProminent)
                    }
                } else {
                    Button {
                        Task {
                            if session.phase == .listening { await session.stopListeningAndSend() }
                            else { await session.startListening() }
                        }
                    } label: {
                        Image(systemName: session.phase == .listening ? "stop.circle.fill" : "mic.circle.fill")
                            .font(.system(size: 72))
                    }
                    .accessibilityLabel(session.phase == .listening ? Text("Stop listening") : Text("Start listening"))
                    .disabled(session.phase == .thinking)
                }

                // Wejście tekstowe — przydatne do testów w symulatorze
                HStack {
                    TextField("Type a command", text: $typed)
                        .textFieldStyle(.roundedBorder)
                        .accessibilityIdentifier("commandField")
                    Button("Send") {
                        let t = typed; typed = ""
                        Task { await session.send(t) }
                    }
                    .disabled(typed.isEmpty || session.phase == .thinking)
                }
                .padding(.horizontal)
            }
            .padding(.bottom)
            .navigationTitle(Text(verbatim: "Hejo"))
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .topBarLeading) {
                    Button("Reset") { session.reset() }
                }
                ToolbarItem(placement: .topBarTrailing) {
                    Button { showSettings = true } label: { Image(systemName: "gearshape") }
                        .accessibilityLabel(Text("Settings"))
                }
            }
            .sheet(isPresented: $showSettings) { SettingsView() }
            .sheet(isPresented: $session.needsConsent) { ConsentView() }
            .onAppear { if !session.hasConsent { session.needsConsent = true } }
        }
    }
}
