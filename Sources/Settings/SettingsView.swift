import SwiftUI

struct SettingsView: View {
    @Environment(AssistantSession.self) private var session
    @Environment(\.dismiss) private var dismiss
    @State private var mode: BackendMode = .direct
    @State private var apiKey = ""
    @State private var hasKey = false
    @State private var error: String?
    @State private var consentDate: Date?

    private let settings = AssistantSettings()

    var body: some View {
        NavigationStack {
            Form {
                Section {
                    // Build sklepowy nie ma proxy (puste PROXY_URL), więc wybór trybu znika.
                    if settings.availableModes.count > 1 {
                        Picker("Backend", selection: $mode) {
                            Text("Own API key").tag(BackendMode.direct)
                            Text("Self-hosted proxy").tag(BackendMode.proxy)
                        }
                    }
                } footer: {
                    Text(mode == .direct
                         ? "Requests go straight from this iPhone to api.anthropic.com and are billed to your key."
                         : "Requests go to the proxy set in Config.local.xcconfig at build time.")
                }

                if mode == .direct {
                    Section {
                        SecureField(hasKey ? "Key saved — paste to replace" : "sk-ant-…", text: $apiKey)
                            .textInputAutocapitalization(.never)
                            .autocorrectionDisabled()
                            .accessibilityIdentifier("apiKeyField")
                        if hasKey {
                            Button("Remove key", role: .destructive) {
                                do {
                                    try settings.keychain.delete()
                                    hasKey = false
                                    // Klient rozmowy trzyma klucz w pamięci — bez tego usunięty
                                    // klucz działałby dalej do zapisu Ustawień albo restartu.
                                    session.reloadSettings()
                                } catch { self.error = error.localizedDescription }
                            }
                        }
                    } header: {
                        Text("Anthropic API key")
                    } footer: {
                        Text("Stored only in this device's Keychain. You can create a key in the Anthropic Console; its use is subject to Anthropic's terms.")
                    }
                }

                Section {
                    if let consentDate {
                        LabeledContent("Sending to Anthropic", value: consentDate.formatted(date: .abbreviated, time: .shortened))
                        Button("Withdraw consent", role: .destructive) {
                            session.revokeConsent()
                            self.consentDate = nil
                        }
                        .accessibilityIdentifier("withdrawConsent")
                    } else {
                        LabeledContent("Sending to Anthropic", value: String(localized: "Not allowed"))
                        Button("Review and allow…") {
                            dismiss()
                            session.needsConsent = true
                        }
                    }
                    Link("Privacy Policy", destination: AppLinks.privacyPolicy)
                } header: {
                    Text("Privacy")
                } footer: {
                    Text("Answers are generated by AI (Claude by Anthropic) and may be inaccurate.")
                }

                if let error {
                    Text(error).foregroundStyle(.red)
                }
            }
            .navigationTitle("Settings")
            .toolbar {
                ToolbarItem(placement: .confirmationAction) {
                    Button("Save") { save() }
                }
                ToolbarItem(placement: .cancellationAction) {
                    Button("Cancel") { dismiss() }
                }
            }
            .onAppear {
                mode = settings.mode
                hasKey = settings.hasAPIKey
                consentDate = session.settings.consent.grantedAt
            }
        }
    }

    private func save() {
        let key = apiKey.trimmingCharacters(in: .whitespacesAndNewlines)
        do {
            if !key.isEmpty { try settings.keychain.save(key) }
            settings.mode = mode
            apiKey = ""
            session.reloadSettings()
            dismiss()
        } catch {
            self.error = error.localizedDescription
        }
    }
}
