import SwiftUI

/// Ujawnienie i zgoda przed pierwszym zapytaniem do Anthropic (App Review 5.1.2(i)) oraz
/// informacja, że odpowiada AI (AI Act art. 50(1)). Bez zgody nic nie wychodzi z telefonu.
struct ConsentView: View {
    @Environment(AssistantSession.self) private var session
    @Environment(\.dismiss) private var dismiss

    var body: some View {
        NavigationStack {
            List {
                Section {
                    Label("Hejo is an AI assistant. Answers are generated by Claude, an AI model by Anthropic, and may be inaccurate.",
                          systemImage: "sparkles")
                }

                Section("What is sent") {
                    Label("The text of what you say (transcribed speech), not the audio.", systemImage: "text.quote")
                    Label("Event dates and titles when you ask about your calendar.", systemImage: "calendar")
                    Label("The text of reminders you create.", systemImage: "checklist")
                    Label("Names of Shortcuts you ask to run.", systemImage: "square.stack.3d.up")
                    #if HOMEKIT_ENABLED
                    Label("Names of HomeKit accessories, rooms and scenes.", systemImage: "house")
                    #endif
                }

                Section("Where it goes") {
                    if session.settings.mode == .direct {
                        Text("Directly from this iPhone to Anthropic (USA), under your own agreement with Anthropic and billed to your API key. RenaCode does not receive or store this data.")
                    } else {
                        Text("To the self-hosted proxy set in this build, which forwards it to Anthropic (USA).")
                    }
                    Text("Speech is transcribed by Apple: on this iPhone when possible, otherwise on Apple's servers.")
                }

                Section {
                    Text("You can withdraw consent at any time in Settings → Privacy. Without consent nothing is sent.")
                    Link("Privacy Policy", destination: AppLinks.privacyPolicy)
                    Link("Anthropic Privacy Policy", destination: AppLinks.anthropicPrivacy)
                }
            }
            .navigationTitle("Before you start")
            .safeAreaInset(edge: .bottom) {
                VStack(spacing: 8) {
                    Button {
                        session.grantConsent()
                        dismiss()
                    } label: {
                        Text("I agree").frame(maxWidth: .infinity)
                    }
                    .buttonStyle(.borderedProminent)
                    .controlSize(.large)
                    .accessibilityIdentifier("consentAgree")
                    Button("Not now") {
                        session.needsConsent = false
                        dismiss()
                    }
                    .accessibilityIdentifier("consentNotNow")
                }
                .padding()
                .background(.bar)
            }
            .interactiveDismissDisabled()
        }
    }
}
